// Regenerates src/shared/psl-data.js from the Public Suffix List (https://publicsuffix.org).
// Run: node scripts/update-psl.mjs   (then run the tests and commit psl-data.js)
import { writeFile } from "node:fs/promises";
import { join } from "node:path";
import { domainToASCII } from "node:url";

const URL_ = "https://publicsuffix.org/list/public_suffix_list.dat";
const text = await (await fetch(URL_)).text();
// Both sections: ICANN suffixes (co.uk) and private ones (github.io), where different owners
// share a parent domain, so each must count as a separate site.
const rules = text.split("\n").map((l) => l.trim()).filter((l) => l && !l.startsWith("//"))
  .map((r) => {
    const [, prefix, name] = r.match(/^([!*]\.?|)(.*)$/);
    return prefix + domainToASCII(name); // URLs give hosts in punycode
  });
if (rules.length < 5000) throw new Error(`only ${rules.length} rules: download failed?`);
await writeFile(join(import.meta.dirname, "..", "src", "shared", "psl-data.js"),
  `// Generated by scripts/update-psl.mjs from ${URL_} on ${new Date().toISOString().slice(0, 10)}. Do not edit.\n`
  + `export const PSL = ${JSON.stringify(rules.join("\n"))};\n`);
console.log(`psl-data.js: ${rules.length} rules`);
